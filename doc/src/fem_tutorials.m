%% Tutorials
% Runnable scripts that explain the toolbox step by step. Each one builds
% its own geometry and, where possible, checks its results against theory.
% The source files are in the |tutorials| folder; run them section by
% section in the Editor.
%
% # <tut01_firstModel.html Your First Model>: the workflow from STL to
%   modes, checked against Euler-Bernoulli
% # <tut02_meshing.html Meshing>: |meshSTL| options, Tet4 vs Tet10
%   convergence, Gmsh GUI meshes, |Scale| and |transform|
% # <tut03_materials.html Materials and Mass>: orthotropic materials, mass
%   properties from M, consistent vs lumped mass
% # <tut04_ties.html Ties and Interfaces>: non-matching meshes, bonded ties,
%   |Tol|, partial bonding, elastic interfaces
% # <tut05_loadsStatics.html Loads and Statics>: dofs, supports, point loads,
%   gravity, reactions
% # <tut06_rigidBodies.html Rigid Bodies>: reference dofs, tip masses,
%   |RefPoint|, mesh-free rigid bodies
% # <tut07_joints.html Couplings and Joints>: joint types, springs, locking,
%   mechanism modes, posing, closed loops, belt transmissions
% # <tut08_dynamics.html Dynamics>: Rayleigh damping, frequency response,
%   Newmark time integration, state space
% # <tut09_reduction.html Model Reduction>: Guyan and Craig-Bampton,
%   recovering the full field
